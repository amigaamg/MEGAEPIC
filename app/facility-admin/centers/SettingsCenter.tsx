function SectionCard({ title, subtitle, children, action }: { title: string; subtitle?: string; children: React.ReactNode; action?: React.ReactNode }) {
  return (
    <div style={{ background: '#fff', border: `1px solid ${C.border}`, borderRadius: 14, padding: 18 }}>
      <div style={{ display: 'flex', alignItems: 'center', justifyContent: 'space-between', marginBottom: 12, flexWrap: 'wrap', gap: 8 }}>
        <div>
          <div style={{ fontSize: 15, fontWeight: 800, color: C.navy, margin: 0 }}>{title}</div>
          {subtitle && <div style={{ fontSize: 11, color: C.muted, marginTop: 2 }}>{subtitle}</div>}
        </div>
        {action}
      </div>
      {children}
    </div>
  );
}

const inputStyle: React.CSSProperties = { width: '100%', height: 34, borderRadius: 8, border: `1px solid ${C.border}`, padding: '0 10px', fontSize: 12, outline: 'none', background: '#fff', color: C.navy, fontFamily: 'inherit' };

function Label({ children }: { children: React.ReactNode }) {
  return <div style={{ fontSize: 10, color: C.muted, display: 'block', marginBottom: 4, textTransform: 'uppercase', fontWeight: 700 }}>{children}</div>;
}

function Field({ label, value, onChange, area, icon: Icon }: { label: string; value: string; onChange: (v: string) => void; area?: boolean; icon?: any }) {
  return (
    <div>
      <Label>{label}</Label>
      {area
        ? <textarea value={value} onChange={(e) => onChange(e.target.value)} rows={2} style={{ ...inputStyle, height: 'auto', padding: '8px 10px', fontFamily: 'inherit' }} />
        : <div style={{ display: 'flex', alignItems: 'center', gap: 6 }}>
            {Icon && <Icon size={14} color={C.muted} />}
            <input value={value} onChange={(e) => onChange(e.target.value)} style={{ ...inputStyle, flex: 1 }} />
          </div>}
    </div>
  );
}

function ToggleChip({ label, on, onClick, tone }: { label: string; on: boolean; onClick: () => void; tone?: string }) {
  const c = tone || C.sky;
  return <button onClick={onClick} style={{ padding: '7px 12px', borderRadius: 20, border: 'none', background: on ? `${c}18` : '#eef2f7', color: on ? c : C.slate, fontSize: 11, fontWeight: 700, cursor: 'pointer' }}>{on ? '✓ ' : ''}{label}</button>;
}

function StatCard({ label, value, tone, icon: Icon }: { label: string; value: string | number; tone?: string; icon?: any }) {
  const c = tone || C.navy;
  return (
    <div style={{ background: '#fff', border: '1px solid #e3e9f2', borderRadius: 14, padding: '14px 16px' }}>
      <div style={{ display: 'flex', alignItems: 'center', gap: 6, marginBottom: 8 }}>
        {Icon && <span style={{ width: 26, height: 26, borderRadius: 8, background: `${c}16`, display: 'flex', alignItems: 'center', justifyContent: 'center' }}><Icon size={14} color={c} /></span>}
      </div>
      <div style={{ fontSize: 19, fontWeight: 800, color: c, textTransform: 'capitalize' }}>{value}</div>
      <div style={{ fontSize: 10, color: C.muted, marginTop: 2, textTransform: 'uppercase', letterSpacing: '.04em' }}>{label}</div>
    </div>
  );
}

function AddBtn({ label, onClick }: { label: string; onClick: () => void }) {
  return <button onClick={onClick} style={{ padding: '7px 14px', borderRadius: 8, border: 'none', background: C.sky, color: '#fff', fontSize: 11, fontWeight: 700, cursor: 'pointer' }}>{label}</button>;
}

function Pill({ label, tone }: { label: string; tone: string }) {
  return <span style={{ padding: '4px 10px', borderRadius: 20, background: `${tone}16`, fontSize: 10.5, fontWeight: 800, color: tone }}>{label}</span>;
}
