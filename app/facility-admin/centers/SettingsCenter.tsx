              <div style={{ width: 64, height: 44, borderBottom: `1.5px solid ${C.navy}`, fontSize: 9, color: C.muted, display: 'flex', alignItems: 'flex-end', justifyContent: 'center', paddingBottom: 4 }}>Dr. J. Otieno</div>
