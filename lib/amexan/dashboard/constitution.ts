// ── Workspace resolution from assignment ───────────────────────────────────────

export function workspaceForAssignment(assignmentKind?: AssignmentKind): ResolvedWorkspace {
  if (!assignmentKind) return { key: 'overview', label: 'Overview', familyId: 'executive', kind: 'overview' };
  const labels: Record<AssignmentKind, string> = {
    ward_round: 'Ward Round', clinic: 'Clinic', theatre: 'Theatre',
    administration: 'Administration', meeting: 'Meeting', research: 'Research',
    teaching: 'Teaching', emergency_call: 'Emergency', icu: 'ICU',
    on_call: 'On Call', laboratory: 'Laboratory', pharmacy: 'Pharmacy',
    radiology: 'Radiology', telemedicine: 'Telemedicine', community_health: 'Community Health',
  };
  return { key: assignmentKind, label: labels[assignmentKind], familyId: 'executive', kind: assignmentKind };
}

