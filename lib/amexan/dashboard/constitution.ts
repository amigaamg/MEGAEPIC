// Constitutional note: a role may legitimately belong to more than one family
// (e.g., chief_pharmacist is both Clinical Leadership and Pharmacy). The engine is
// deterministic: it returns the most specific operational family that declares the
// role — the last declaration in the constitutional registry — so a Chief Pharmacist
// receives the Pharmacy operating system, not the aggregated leadership one.
export function resolveFamily(roles: string[]): DashboardFamilyId | undefined {
  let resolved: DashboardFamilyId | undefined;
  for (const role of roles) {
    for (const family of DASHBOARD_FAMILIES) {
      if (family.roles.includes(role.toLowerCase())) resolved = family.familyId;
    }
  }
  return resolved;
}

// ── Family label lookup ────────────────────────────────────────────────────────

export function familyLabel(familyId: DashboardFamilyId): string {
  return DASHBOARD_FAMILIES.find(f => f.familyId === familyId)?.label ?? `${familyId} Dashboard`;
}

